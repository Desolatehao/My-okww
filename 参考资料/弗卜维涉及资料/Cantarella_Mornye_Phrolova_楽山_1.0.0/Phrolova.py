    def wait_lib_energy(self, char, level, cap, tag='能量', poke=True,
                        interval=None, read_every=0.10, confirm=2):
        """边打边等【大招能量到 level】, 到了立刻返回。

        跟 wait_lib_ready 的区别: 那个用的是框架的 liberation_available()(布尔),
        对某些角色恒为 True; 这个读的是能量条的【占比】, 分得出"还差多少"。
        【打不满也往下走】: 上限到了就返回 False, 调用方自己决定要不要照样按 R。
        """
        interval = self.A_INTERVAL if interval is None else interval
        start = time.time()
        n = reads = streak = 0
        pct = 0.0
        best = 0.0
        ok = False
        next_click = start
        next_read = start
        while time.time() - start < cap:
            now = time.time()
            if poke and now >= next_click:
                self.click()
                n += 1
                next_click += interval
                if next_click < now:
                    next_click = now + interval
            now = time.time()
            if now >= next_read:
                next_read = now + read_every
                reads += 1
                self.task.next_frame()
                try:
                    pct = self.lib_energy(char)
                except Exception:
                    pct = 0.0
                best = max(best, pct)
                streak = streak + 1 if pct >= level else 0
                if streak >= confirm:
                    ok = True
                    break
            nap = min(next_click if poke else next_read, next_read) - time.time()
            if nap > 0:
                self.macro_wait(min(nap, 0.02))
        self.macro_mark(f'{tag}({"满" if ok else "不够"}{best:.2f},A x{n},读x{reads},'
                        f'{time.time() - start:.2f}s)')
        return ok

    def f_break_then_hold(self, tag='处决', wait_break=None, f_interval=None,
                          anim_cap=None, settle=None, tail=None, blind_hold=None,
                          keep_held=False, probe=None):
        """连发处决键; 【处决演出一开始才按住左键(预输入重击)】; 演完松手。

        (用户 2026-08-31: "处决后没变身, 应该在处决的时候开始预输入重击, 你好像搞反了")

        【为什么不能从大招演出就一直按住】—— 我上一版就是这么写的, 反了:
        那样重击会在【大招演完那一刻】就出手, 8 秒强化状态从那时候开始烧;
        紧接着的处决演出(带全局时停, 最长好几秒)把它吃掉一大截 ——
        处决完人已经不是强化状态了, 表现出来就是"处决后没变身"。
        按住必须压在【处决演出】上, 让那一下重击落在处决【之后】,
        8 秒才从那一刻开始算。

        两段:
          1. 连发 F + 连点普攻, 等处决演出开始(队伍 HUD 掉下去)。
             【演出里的按键被丢掉】, 所以要连发不能单发。
          2. HUD 一掉就 mouse_down 按住, 一直按到演出结束(HUD 连续回来 settle 秒),
             再多按 tail 秒松手 —— 重击就在这一刻出手。

        【等不到处决也要按住】(blind_hold): 谐度不是每圈都破得掉, 但那 8 秒强化状态
        是这一整段伤害的来源, 不能因为没处决就不要了。

        Returns: 处决有没有触发。
        """
        wait_break = self.CAN_F_WAIT if wait_break is None else wait_break
        f_interval = self.CAN_F_INTERVAL if f_interval is None else f_interval
        anim_cap = self.F_ANIM_TIME_OUT if anim_cap is None else anim_cap
        settle = self.CAN_ANIM_SETTLE if settle is None else settle
        tail = self.CAN_HEAVY_TAIL if tail is None else tail
        blind_hold = self.CAN_FALLBACK_HOLD if blind_hold is None else blind_hold
        probe = self.CAN_F_PROBE if probe is None else probe
        # ---- 1 连发 F, 等处决演出开始 ----
        start = time.time()
        nf = n = 0
        broke = False
        seen_f = not self.USE_F_BREAK   # 关掉处决时不探, 直接走"没提示"那条路
        no_f = False
        next_f = next_click = next_probe = start
        while time.time() - start < wait_break:
            now = time.time()
            if self.USE_F_BREAK and now >= next_f:
                self.task.send_key('f', after_sleep=0)
                nf += 1
                next_f += f_interval
                if next_f < now:
                    next_f = now + f_interval
            now = time.time()
            if now >= next_click:
                self.click()
                n += 1
                next_click += self.A_INTERVAL
                if next_click < now:
                    next_click = now + self.A_INTERVAL
            self.task.next_frame()
            if not self.task.in_team()[0]:
                broke = True
                break
            # ---- 没有处决提示就别把窗口等满 ----: 见 CAN_F_PROBE
            now = time.time()
            if not seen_f and now >= next_probe:
                next_probe = now + self.CAN_F_PROBE_INTERVAL
                try:
                    if self.task.find_one('f_break_full', threshold=self.CAN_F_TPL):
                        seen_f = True
                except Exception:
                    # 【读不到就当没看见】: 这个方向是安全的 —— 顶多退回原来那套
                    # "等满窗口", 不会误判成"有处决"而把重击往后拖
                    pass
            if not seen_f and time.time() - start >= probe:
                no_f = True
                break
            self.macro_wait(0.01)
        self.macro_mark(f'{tag}({"触发" if broke else ("无提示" if no_f else "无")},'
                        f'F x{nf},A x{n},{time.time() - start:.2f}s)')
        # ---- 2 按住左键: 预输入重击 ----
        self.task.mouse_down()
        self.holding_attack = True
        hold_start = time.time()
        back_since = None
        back = False
        try:
            if broke:
                while time.time() - hold_start < anim_cap:
                    self.task.next_frame()
                    if not self.task.in_team()[0]:
                        back_since = None
                    elif back_since is None:
                        back_since = time.time()
                    elif time.time() - back_since >= settle:
                        back = True
                        break
                    self.macro_wait(0.01)
                # 处决演出计入 freeze, 否则框架会把它算成"这个角色磨蹭了几秒"
                self.add_freeze_duration(hold_start, time.time() - hold_start)
            else:
                self.macro_wait(blind_hold)
            if tail > 0:
                self.macro_wait(tail)
        finally:
            # 【keep_held: 不松手, 交给调用方接着按】(用户 2026-09-01: "把从F开始
            # 预输入的重击一直持续到切人位置, 保持一致长按攻击键的状态")。
            # 【只有异常路径才在这里松】—— 正常路径松手的责任在调用方,
            # 而 perform_loop 的 finally 里还有一道 release_attack 兜底
            if not keep_held:
                self.release_attack()
        self.macro_mark(f'{tag}按住({"ok" if (back or not broke) else "timeout"},'
                        f'{time.time() - hold_start:.2f}s{",不松手" if keep_held else ""})')
        return broke

