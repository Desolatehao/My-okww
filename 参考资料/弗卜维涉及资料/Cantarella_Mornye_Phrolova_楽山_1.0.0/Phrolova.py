        # 【全队一圈只在坎那一格打处决】: 那边处决演出跟大招演出串在一起、
        # 预输入重击压在处决后面, 一次演出把两件事都办了(见 f_break_then_hold)。
        # 放在莫宁这里的话, 处决演出带全局时停, 会把"A -> E -> 强化重击"整条线拖散 ——
