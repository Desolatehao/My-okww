    def spam_ae(self, char, cap, stop, tag='AE连发', a_interval=None, e_interval=None,
                f_interval=None, read_every=0.10, min_wait=0.0):
        """【A 和 E 一起连发】, 各走各的节奏: 点普攻 / 发 E / (发 F) / 读屏。

        坎特蕾拉那一整段用的就是这个(用户 2026-08-31 给的口径, 见 CAN_AE_A_INTERVAL
        上面那段)。E 落在 CD 上是空操作、不花钱, 所以不用算"什么时候该按" ——
        强化E 一亮就会被下一次连发按掉。

        【三个节奏必须解耦】: 挂在一起的话点击会被 E 的间隔或者读屏的耗时卡住,
        表现出来就是"A一下停一下"(这条轴上栽过一次)。

        Args:
            stop: 每次读屏【之后】调一次, 返回 True 就停。它自己负责读它要的东西
                (画面已经由本函数 next_frame 刷好了)。
            f_interval: 顺带按处决键的间隔(None = 不按)。
                【处决是"随时"的, 不是排在某一格的】(用户 2026-08-31: "坎的F不必在
                这么后啊, R后随时处决就行")。谐度什么时候破由怪说了算, 排在固定位置
                要么早了(白按)要么晚了(错过窗口) —— 掺进连发里最省事,
                没得打的时候按 F 什么也不会发生。
                【所以这里【不】调 spam_f】: 那个是阻塞的 —— 一触发就要
                poke_until_hud_back 等整个演出。掺在连发里只需要把键递出去,
                演出来了下面的"HUD 不在就不判"自己会处理。

        【演出/时停期间不判 stop】: 处决(或者任何演出)一触发队伍 HUD 就掉下去,
        这时候读到的亮度、协奏全是假的 —— 直接跳过那几次读屏, 并且把这段时间
        【从 cap 里扣掉】, 免得一次处决把整格的预算吃光。
        """
        a_interval = self.A_INTERVAL if a_interval is None else a_interval
        e_interval = self.KEY_INTERVAL if e_interval is None else e_interval
        start = time.time()
        na = ne = nf = reads = 0
        anim = 0.0
        anim_from = None
        hit = False
        next_a = next_e = next_f = start
        next_read = start + max(0.0, min_wait)
        while time.time() - start - anim < cap:
            now = time.time()
            # 【a_interval 给 0 就完全不点】: 坎的收尾在"一路按住左键"那一档时要用 ——
            # 按住期间再插点击会把长按打断
            if a_interval and now >= next_a:
                self.click()
                na += 1
                next_a += a_interval
                if next_a < now:
                    next_a = now + a_interval
            now = time.time()
            # 【e_interval 给 0 就只连点、不发 E】: "等强化E 亮"那一格要用 ——
            # 一边盲发 E 一边等它亮是矛盾的, E 会把刚亮的那一帧当场按掉,
            # 读屏永远看不见(实机症状: 判据跑满上限, Q 晚了 8 秒)
            if e_interval and now >= next_e:
                char.send_resonance_key()
                ne += 1
                next_e += e_interval
                if next_e < now:
                    next_e = now + e_interval
            now = time.time()
            if f_interval and self.USE_F_BREAK and now >= next_f:
                self.task.send_key('f', after_sleep=0)
                nf += 1
                next_f += f_interval
                if next_f < now:
                    next_f = now + f_interval
            now = time.time()
            if now >= next_read:
                next_read = now + read_every
                reads += 1
                self.task.next_frame()
                if not self.task.in_team()[0]:
                    # 演出里: 判据不可信, 只记时间不判
                    if anim_from is None:
                        anim_from = now
                else:
                    if anim_from is not None:
                        anim += time.time() - anim_from
                        anim_from = None
                    try:
                        if stop():
                            hit = True
                            break
                    except Exception:
                        pass
            targets = [next_read]
            if a_interval:
                targets.append(next_a)
            if e_interval:
                targets.append(next_e)
            nap = min(targets) - time.time()
            if nap > 0:
                self.macro_wait(min(nap, 0.02))
        if anim_from is not None:
            anim += time.time() - anim_from
        if anim > 0:
            # 演出那一段计入 freeze, 否则框架会把它算成"这个角色磨蹭了几秒"
            self.add_freeze_duration(time.time() - anim, anim)
        self.macro_mark(f'{tag}({"ok" if hit else "cap"},A x{na},E x{ne}'
                        f'{f",F x{nf}" if nf else ""}'
                        f'{f",演出{anim:.1f}s" if anim > 0 else ""},'
                        f'读x{reads},{time.time() - start:.2f}s)')
        return hit

    def wait_e_cd_or_ring(self, char, cd_left):
        """等普通E 的 CD 转好, 但【粉环先亮就提前返回】。

        返回 'cd'(等到 CD 转好) / 'ring'(强化E 先亮了) / 'ready'(压根不用等)。

        【为什么两件事要合成一个等待】: 分两步写的话第二步会从头开始重新等 ——
        弗洛洛那边的 wait_heavy_ready 就是被这个坑逼出来的。
        【等的期间不出手】: 左键还按着, 强化A 自己在打; 这里只刷新画面
        """
        if cd_left <= 0:
            return 'ready'
        end = time.time() + cd_left
        next_read = time.time()
        hits = 0
        best = 0.0
        while time.time() < end:
            now = time.time()
            if now >= next_read:
                next_read = now + self.CAN_E2_RING_INTERVAL
                self.task.next_frame()
                try:
                    v = self.ee_ring_pct(char)
                except Exception:
                    v = 0.0
                if v > best:
                    best = v
                # 【连读才认】: 见 CAN_E2_RING_CONFIRM。中间断一次就清零 ——
                # 闪光是一两帧, 环是持续亮的, 清零把两者分得干干净净
                hits = hits + 1 if v >= self.CAN_EE_RING_FILL else 0
                if hits >= self.CAN_E2_RING_CONFIRM:
                    self.macro_mark(f'坎E让位强化E(环{v:.3f})')
                    return 'ring'
            self.macro_wait(0.02)
        self.macro_mark(f'坎等E转好({cd_left:.1f}s,环最高{best:.3f})')
        return 'cd'

    def ee_ring_pct(self, char=None):
        """强化E 那圈粉环的占比。判据框 = 框架的 box_resonance 外扩一圈。

        【全用原版 OK 的 API】(用户 2026-08-31: "我需要打包到工坊"):
        get_box_by_name / Box.scale / calculate_color_percentage 都是框架自带的,
        没有一行私有的 cv2。
        【框跟着框架走】: box_resonance 是框架按实际截图标注的图标框, 各种分辨率下
        它自己会算对; 我只在它中心上放大, 不去猜屏幕坐标
        """
        box = self.task.get_box_by_name('box_resonance').scale(
            self.CAN_EE_RING_W, self.CAN_EE_RING_H)
        return float(self.task.calculate_color_percentage(
            self.CAN_EE_RING_COLOR, box))

    def ee_ring_probe(self, char, confirm=1):
        """"强化E 亮了"的判据: 粉环出现。给 spam_ae 当 stop 用。"""
        st = self._ee_state

        def probe():
            self.task.next_frame()
            try:
                v = self.ee_ring_pct(char)
            except Exception:
                return False
            if v > st['best']:
                st['best'] = v
            st['lit'] = st['lit'] + 1 if v >= self.CAN_EE_RING_FILL else 0
            return st['lit'] >= confirm

        return probe

    def ee_bright_probe(self, char, bright, confirm=1):
        """给 spam_ae 用的 stop: 【E 图标亮了】= 强化E 就绪。

        (用户 2026-08-31: "坎特的强化E有时候会提前, 所以不能用时间来判断Q,
         应该说按下了强化E就开始按Q")

        【跟 ee_fired_probe 的区别, 以及为什么换成这个】: 那个判的是"亮过又不亮了"
        = 被按掉了 —— 但它跟"一边盲发 E"是矛盾的: E 一亮就被自己的连发按掉,
        读屏根本没机会看到亮的那一帧, 判据永远不成立, 跑满上限。
        现在改成【自己控制那一下】: 这一段只连点不发 E, 一读到亮就退出去,
        由调用方按 E, 按完立刻开始按 Q —— "按下了强化E就开始按Q"。
        """
        st = self._ee_state

        def probe():
            pct = float(char.current_resonance())
            st['best'] = max(st['best'], pct)
            st['lit'] = st.get('lit', 0) + 1 if pct >= bright else 0
            return st['lit'] >= confirm
        return probe

    def ee_fired_probe(self, char, bright, dark_confirm):
        """给 spam_ae 用的 stop: 【图标先亮过, 再看到它不亮】= 强化E 被按掉了。

        【只读亮度, 不读 OCR】: current_resonance() 是一个 90x68 小框的纯白像素占比,
        比模板匹配和 CD 的 OCR 都便宜得多, 而且【不会像 OCR 那样漏读一帧就假阳性】
        (refresh_cd 漏读时三个 CD 全变 0, 见 wait_e_ready 里的说明)。
        实测: 挂着 CD 0.016~0.041 / 强化E 就绪 0.122~0.171。
        """
        st = self._ee_state

        def probe():
            pct = float(char.current_resonance())
            st['best'] = max(st['best'], pct)
            if pct >= bright:
                st['ready'] = True
                st['dark'] = 0
                return False
            if st['ready']:
                st['dark'] += 1
                return st['dark'] >= dark_confirm
            return False
        return probe

    def wait_forte_spent(self, char, cap, dark, tag='回路打空', poke=True,
                         interval=None, read_every=0.08, min_wait=0.0):
        """边打边等【回路条右边那个指示灭掉】= 回路被强化A 吃完了。

        坎特蕾拉的交棒判据(用户 2026-08-31: "回路没消耗完之前她回路条右边的指示
        一直都是亮的, 消耗完了再切弗洛洛")。

        【同一个 mouse_forte 模板, 在她身上好用、在莫宁身上读不到】—— 这就是
        "不是每个角色都做了检测"的具体样子, 用之前先看类文档里那张审计表。

        【要求"连续灭够 dark 秒"而不是"灭了一帧"】: 实测她那一段中间会有两次
        0.2 秒左右的短暂熄灭(出招时图标没渲染), 只看单帧会提前 5 秒交棒。

        【⚠ 别再加"先看到它亮过"这个条件】(2026-08-31 栽过): 直觉上那样能挡住
        "一进门就误判", 实际后果是【回路要是在进这一格之前就打完了, 判据永远不成立】,
        只能跑满上限 —— 用户的原话是"回路已经打完了还不切弗洛洛"。
        要挡进门那几帧就用 min_wait, 不要用 seen_lit。
        (下面这个 seen_lit 是给"从头到尾没亮过 = 压根没进强化状态"那条早退用的,
         不参与"算不算打空"的判定。)

        【到上限也往下走】: 被怪打断、回路没吃完是常事(用户: "那也没关系,
        直接走弗洛洛的流程就行") —— 卡在这里比少打几下强化A 糟得多。
        """
        interval = self.A_INTERVAL if interval is None else interval
        start = time.time()
        n = 0
        reads = 0
        spent = False
        dark_since = None
        seen_lit = False
        next_click = start
        next_read = start + max(0.0, min_wait)
        while time.time() - start < cap:
            now = time.time()
            if poke and now >= next_click:
                self.click()
                n += 1
                next_click += interval
                if next_click < now:
                    next_click = now + interval
            now = time.time()
            if now >= next_read:
                next_read = now + read_every
                reads += 1
                self.task.next_frame()
                try:
                    lit = bool(char.is_mouse_forte_full())
                except Exception:
                    lit = True          # 读不出来当作"还亮着", 宁可多打几下
                if lit:
                    seen_lit = True
                    dark_since = None
                elif dark_since is None:
                    dark_since = now
                elif now - dark_since >= dark:
                    spent = True
                    break
                # 【从头到尾就没亮过 = 压根没进强化状态】(大招丢了、重击没接上)。
                # 这时候没有回路可打空, 跑满上限纯亏, 早点走人
                if not seen_lit and now - start >= min_wait + self.CAN_FORTE_NOLIT:
                    break
            nap = min(next_click if poke else next_read, next_read) - time.time()
            if nap > 0:
                self.macro_wait(min(nap, 0.02))
        self.macro_mark(f'{tag}({"空" if spent else "cap"},'
                        f'{"见过亮" if seen_lit else "没见过亮"},'
                        f'A x{n},读x{reads},{time.time() - start:.2f}s)')
        return spent

    def wait_e_ready(self, char, cap, tag='E亮', poke=True, interval=None,
                     read_every=0.10, min_wait=0.0, bright=0.08, confirm=2):
        """边打边等【E 图标亮起来】(不再显示 CD 读数), 亮了立刻返回。

        坎特蕾拉的强化E 专用(用户 2026-08-31: "坎的强化E都亮了你没马上按")。
        【判据是两条 AND, 而且要连着读到几次】(用户 2026-08-31 实机: "有一次坎没有
        按强化E 而且提前切弗洛洛了, 坎协奏都没满")。
        【只看"CD 读数消失"会假阳性】: refresh_cd 是【先把三个 CD 全清零, OCR 读到
        什么才填回去】—— OCR 一次没读出来(特效糊住数字/数字正在换)三个就全是 0,
        这一格当场认为"强化E 好了"。按下去是空操作(E 其实还在 CD), 后面 1.9 秒、Q、
        协奏没满就切人, 一串全塌。
        【所以再加一条正向判据: 图标亮不亮】。录像量的 E 图标框纯白像素占比:
            挂着 CD 读数         0.016 ~ 0.041
            换图标、没读数(过渡)  0.000
            强化E 就绪(发亮)      0.122 ~ 0.171   <- 三四倍的分离
        这正是框架 current_resonance() 的算法(text_white_color 244-255)。
        两条都成立、并且连着 confirm 次才认。

        【方向很重要】: 这一格是"条件成立就往下走", 假阳性直接毁掉后面一串;
        而 press_e_until_fired / fire_echo_until_fired 是"条件成立就停手发键",
        假阳性只是多按几下, 无害。同一个 get_cd, 用在两个方向上风险完全不同。

        【为什么不用固定秒数】: 那一段实测 6.5 秒, 但它取决于这一轮打出了多少强化A
        (每下吃一格回路), 被打断就会推后。定时要么早按(空操作)要么晚按(干等)。

        【回路条右边那个 mouse_forte 在这里不适用】: 那是"长按重击"的提示,
        她整段强化状态里一直亮着(录像 75.65~79.55), 分不出强化E 就绪没有。
        """
        interval = self.A_INTERVAL if interval is None else interval
        start = time.time()
        n = 0
        reads = 0
        ready = False
        streak = 0
        nocd_streak = 0
        pct = 0.0
        best = 0.0
        next_click = start
        next_read = start + max(0.0, min_wait)
        while time.time() - start < cap:
            now = time.time()
            if poke and now >= next_click:
                self.click()
                n += 1
                next_click += interval
                if next_click < now:
                    next_click = now + interval
            now = time.time()
            if now >= next_read:
                next_read = now + read_every
                reads += 1
                self.task.next_frame()
                try:
                    no_cd = not self.task.has_cd('resonance')
                except Exception:
                    no_cd = False
                try:
                    pct = float(char.current_resonance())
                except Exception:
                    pct = 0.0
                best = max(best, pct)
                streak = streak + 1 if (no_cd and pct >= bright) else 0
                nocd_streak = nocd_streak + 1 if no_cd else 0
                if streak >= confirm:
                    ready = True
                    break
                # 【亮度门槛万一没标准(换分辨率/框对不上)的兜底】: 连着这么多次都读到
                # "没有 CD 读数"也认。OCR 漏读是单帧事件, 不会连着 confirm*3 次都漏
                if nocd_streak >= confirm * 3:
                    ready = True
                    self.logger.info(f'{tag}: 靠"连续 {nocd_streak} 次没读到 CD"判定就绪 '
                                     f'(亮度只到 {pct:.3f} < {bright:.2f}) —— '
                                     f'亮度门槛可能要重标')
                    break
            nap = min(next_click if poke else next_read, next_read) - time.time()
            if nap > 0:
                self.macro_wait(min(nap, 0.02))
        self.macro_mark(f'{tag}({"亮" if ready else "cap"},白{best:.2f},'
                        f'A x{n},读x{reads},{time.time() - start:.2f}s)')
        if not ready:
            self.logger.info(
                f'{tag}: 强化E 判据没成立(最亮 {best:.3f} / 门槛 {bright:.2f}) — '
                f'亮度一直上不去就是这一轮强化A 打得不够、回路没吃完; '
                f'要是画面上明明亮了, 调 bright 那个门槛(它跟 box_resonance 这个框的'
                f'大小有关, 换分辨率可能要重标)')
        return ready

