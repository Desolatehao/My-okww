    def wait_mouse_forte(self, char, cap, min_wait=0.0, tag='长按提示', poke=True,
                         interval=None, read_every=0.10):
        """边连点边等准星旁的【长按重击提示】亮起来, 亮了立刻返回。

        【弗洛洛那一段现在不走这里, 走 wait_heavy_ready】(它要同时等协奏那一条)。
        这个留着是因为它是"只等长按提示"的最小形态 —— 想把某一格单独拆出来调,
        或者别的角色要用, 直接调它。

        这是这条轴上最重要的一个读屏判据 —— 三个人的"该长按了"都是它:
          弗洛洛: 六个乐声满 -> 可以出强化重击
          莫宁:   核心满(E1-伤害 给 100 点) -> 可以出观测重击
        判据用的是框架自带的 find_mouse_forte()(模板匹配 + 二值化), 不是自己数图标。

        【连点期间可能读不到这个图标】: 莫宁那边就是这样(她一直在出招, 图标没渲染),
        清达莫为此在连点里挖了 MOR_READ_PAUSE 的停顿。弗洛洛这边实机是读得到的,
        所以没挖 —— 哪天她也卡在"重击闸门(乐声?)"上, 照 mor_hold_heavy 那个形状改。

        【为什么不按固定时长】: 攒资源的速度取决于每一下有没有打中, 转火/位移都会
        让它浮动。实机三圈"变奏 -> 六个乐声"分别是 7.1 / 7.0 / 6.9 秒, 看着稳,
        但那是没脱手的理想情况; 打歪一下就要多走一整轮连段。

        Args:
            min_wait: 【这之前一律不认】。参考录像里这个提示在乐声还没满的时候
                会闪一下(单帧), 一读到就长按的话就是拿五个乐声去出强化重击 ——
                招出得去, 但后面那一发大招少一层, 整圈的伤害都不对。
                所以压一个下界: 比"最快能攒满"再短一点, 只挡误判、不当等待用。
            read_every: 两次读屏之间至少隔这么久。见下面那段【必须解耦】。

        【点击的节奏和读屏的节奏必须各走各的】(用户 2026-08-31 指出"A一下停一下"):
        原来是"点一下 -> next_frame -> 模板匹配 -> 再回到点击", 一圈要 0.05~0.09 秒,
        于是点击实际落在 0.12~0.20 秒一下, 而不是 interval 说的那个数。
        这一格盖的是弗洛洛攒乐声最长的那一段, 八九个派生点每个晚 0.1 秒就累出快一秒。
        engine 里 spam_key 早就写过同一条(发键和点击各走各的), 我在读屏这边又踩了一次。
        现在: 点击按【绝对时刻表】走(next_click += interval, 不用 now + interval,
        免得读屏耗时一点点累进去), 读屏另开一个 read_every 的节奏。
        """
        interval = self.A_INTERVAL if interval is None else interval
        start = time.time()
        deadline_min = start + max(0.0, min_wait)
        n = 0
        reads = 0
        lit = False
        next_click = start
        next_read = deadline_min      # 到点之前一律不读, 省下来的全给点击
        while time.time() - start < cap:
            now = time.time()
            if poke and now >= next_click:
                self.click()
                n += 1
                # 【累加不重置】: 用 next_click += interval 而不是 now + interval,
                # 后者会把每次点击自身的耗时一点点累进节奏里, 越点越慢
                next_click += interval
                if next_click < now:      # 掉队太多就重新对齐, 别攒出一串补点
                    next_click = now + interval
            now = time.time()
            if now >= next_read:
                next_read = now + read_every
                reads += 1
                self.task.next_frame()
                try:
                    if char.is_mouse_forte_full():
                        lit = True
                        break
                except Exception:
                    pass
            # 【睡到"下一件事"为止】: 睡固定 0.01 秒的话空转一圈也要走一遍循环开销,
            # 点击照样会被挤晚
            nap = min(next_click if poke else next_read, next_read) - time.time()
            if nap > 0:
                self.macro_wait(min(nap, 0.02))
        self.macro_mark(f'{tag}({"亮" if lit else "cap"},A x{n},读x{reads},'
                        f'{time.time() - start:.2f}s)')
        return lit

    def wait_heavy_ready(self, char, con_level, cap, note_min=0.0,
                         tag='重击闸门', poke=True, interval=None, read_every=0.06,
                         dodge_at=0.0):
        """一个循环里【同时】等两件事, 两个都成立就立刻长按重击:
             1) 六个乐声满 —— 准星旁的长按重击提示亮了(find_mouse_forte)
             2) 协奏 >= con_level —— 强化重击(+40)和大招(+20)要从这里起跳才填得满

        【为什么必须合成一个循环】(用户 2026-08-31 实机: "协奏已经过了45你没有马上打
        强化重击还是多A了很多"): 原来是先 wait_mouse_forte 再 wait_con_at_least
        两段【顺序】等 —— 先满的那个满了之后, 后一个还要【从头跑一遍】:
        重新计 min_wait、重新走第一次读屏。早就成立的条件白白又等了一轮。

        【两个判据轮流读, 不是每轮都读两个】: 模板匹配和能量环连通域分析都不便宜,
        挂在一起会把点击挤慢(见 wait_mouse_forte 里那段)。已经成立的那个不再读。

        Args:
            note_min: 乐声这一条在这之前一律不认(提示图标起手会闪单帧)。
        【长按提示是硬条件, 没有"到点强行走"这一说】(用户 2026-08-31 实机:
        "强化重击没放出来"): 我原来加过一个兜底 —— 协奏够了之后再给提示 0.8 秒,
        读不到就照样长按。那是错的: 提示没亮就长按, 出来的是【普通重击】,
        既没有强化重击那 40 点协奏、也拿不到定音状态(=大招不解锁), 整圈全塌。
        宁可多 A 几下等它亮, 也不能空放。

        【提示离线验证过是准的】: 把框架的 mouse_forte 模板抠出来在参考录像上跑,
        它在六个乐声满的那一帧(49.72s -> 判据 49.80s)亮起, score 0.67~0.71,
        阈值 0.6 有余量。所以读不到就是真的没准备好, 不是判据坏了。
        """
        interval = self.A_INTERVAL if interval is None else interval
        start = time.time()
        note_ok_after = start + max(0.0, note_min)
        n = 0
        reads = 0
        notes_ok = False
        con_ok = False
        con = 0.0
        which = 0
        next_click = start
        next_read = start
        con_ok_at = None
        notes_by = ''
        dodged = False
        next_shot = start if self.PHRO_SHOT_FORTE else None
        nshot = 0
        while time.time() - start < cap:
            # ---- 插一发闪避取消后摇 ----: 见 PHRO_DODGE_AT
            # 【放在点击前面】: 闪避发完立刻回来(after_sleep=0), 紧接着的那一下点击
            # 就是"用A把闪避接回去"的那一下
            if dodge_at and not dodged and time.time() - start >= dodge_at:
                dodged = True
                self.dodge(tag='弗闪避')
            now = time.time()
            if poke and now >= next_click:
                self.click()
                n += 1
                next_click += interval
                if next_click < now:
                    next_click = now + interval
            now = time.time()
            if now >= next_read:
                next_read = now + read_every
                reads += 1
                # 轮流读: 已经成立的那一条不再花钱
                if not notes_ok and (con_ok or which % 2 == 0):
                    self.task.next_frame()
                    full, by = self.phro_forte_full(char)
                    if full and time.time() >= note_ok_after:
                        notes_ok = True
                        notes_by = by
                elif not con_ok:
                    try:
                        con = float(char.get_current_con())
                    except Exception:
                        con = 0.0
                    if con >= con_level:
                        con_ok = True
                        con_ok_at = time.time()
                which += 1
                if notes_ok and con_ok:
                    break
            # ---- 连拍标定 ----: 见 PHRO_SHOT_FORTE。【只发一次截图, 不等】,
            # 所以点击时刻表照跑, 这一段的输出一点不受影响
            if next_shot is not None and nshot < self.PHRO_SHOT_FORTE_MAX:
                now = time.time()
                if now >= next_shot:
                    next_shot = now + self.PHRO_SHOT_FORTE_EVERY
                    try:
                        self.task.screenshot(
                            f'phro_forte_{nshot:02d}_{now - start:.2f}s'
                            f'_{"亮" if notes_ok else "暗"}')
                        nshot += 1
                    except Exception:
                        next_shot = None
            nap = min(next_click if poke else next_read, next_read) - time.time()
            if nap > 0:
                self.macro_wait(min(nap, 0.02))
        if dodge_at and not dodged:
            # 【没轮到就说明这一段比 3.6 秒短】: 闸门先成立了, 闪避不该再拖时间
            self.macro_mark('弗闪避跳过(闸门先到)')
        self.macro_mark(f'{tag}(乐声{notes_by + "亮" if notes_ok else "?"},'
                        f'协奏{con:.2f}{"ok" if con_ok else "!"},'
                        f'A x{n},读x{reads},{time.time() - start:.2f}s)')
        if not (notes_ok and con_ok):
            self.logger.info(f'{tag}: gave up after {cap:.1f}s '
                             f'(notes={notes_ok} con={con:.2f}/{con_level:.2f})')
        return notes_ok and con_ok

    def wait_con_at_least(self, char, level, cap, tag='协奏', poke=True,
                          interval=None, read_every=0.12):
        """边连点边等协奏圈涨到 level 以上(0~1)。到上限也往下走, 不把轴卡死。

        【弗洛洛那一段现在不走这里, 走 wait_heavy_ready】(它要同时等乐声那一条)。
        这个留着是"只等协奏门槛"的最小形态, 别处要用直接调。

        跟 wait_con_for_intro 的区别: 那个是"等满了才交棒", 这个是
        【等到某个门槛才做下一个动作】—— 因为后面那两发(强化重击 +40、大招 +20)
        自己还会把圈推上去一大截, 等满再动手就是把那一截白等掉。

        【读协奏不便宜】(能量环的连通域分析), 所以跟点击【分成两个节奏】:
        点击按绝对时刻表走, 读屏另按 read_every。挂在一起就是"A一下停一下"。
        【等的期间必须继续打】: 圈是靠打中才涨的, 干站着等只会等到超时。

        【第一局可能一直读 0】: get_current_con 要先见过一次满圈才知道满圈多大
        (task.con_full_size 是学出来的)。所以读不到不当异常处理, 跑满 cap 往下走。
        """
        interval = self.A_INTERVAL if interval is None else interval
        start = time.time()
        n = 0
        reads = 0
        con = 0.0
        hit = False
        samples = []
        next_click = start
        next_read = start
        while time.time() - start < cap:
            now = time.time()
            if poke and now >= next_click:
                self.click()
                n += 1
                next_click += interval
                if next_click < now:
                    next_click = now + interval
            now = time.time()
            if now >= next_read:
                next_read = now + read_every
                reads += 1
                try:
                    con = float(char.get_current_con())
                except Exception:
                    con = 0.0
                if len(samples) < self.CON_SAMPLE_MAX:
                    samples.append(f'{time.time() - start:.2f}:{con:.2f}')
                if con >= level:
                    hit = True
                    break
            nap = min(next_click if poke else next_read, next_read) - time.time()
            if nap > 0:
                self.macro_wait(min(nap, 0.02))
        self.macro_mark(f'{tag}({con:.2f},{"ok" if hit else "CAP"},A x{n},'
                        f'读x{reads},{time.time() - start:.2f}s)')
        if not hit:
            self.logger.info(f'{tag}: con only reached {con:.2f} (< {level:.2f}) in '
                             f'{cap:.1f}s — {" ".join(samples)}')
        return hit

    def mor_hold_heavy(self, mor, tag='morHold', e_after=None, cap=None, stop_when=None):
        """莫宁的强化重击: 【亮之前一直点, 一亮马上长按】。

        用户 2026-08-21 最终口径: "如果在地上被打断了, 不要笨的一直长按重击, 这样莫宁
        会不连贯。在强化重击没亮之前一直持续点按就行, 亮了马上长按重击"。

        所以这一格是两段:
          1. 【点】—— 连点普攻把回路条充上去, 一直点到强化重击的标记亮起。
             被怪打断了照样在点, 她的动作是连贯的; 而【一直按住】的话被打断之后
             她就卡在一个出不来的蓄力上, 那正是"不连贯"的来源。
          2. 【按】—— 标记一亮【立刻】mouse_down, 判定成立到按下之间不插任何东西
             (不再多点一下、也不重读一次条)。这是"有强化重击就要放, 不要有了
             过了那个点还在A"那条要求。

        这一格前后改了三版, 三版各解决了一个问题, 少哪一半都不行:
          - v1 固定窗口连点 -> 窗口打满条却不一定满(被打断补不回来) -> 退化成普通重击,
            不起飞;
          - v2 连点到条满再长按 -> 中间隔着一次多余的重读, "过了那个点还在A";
          - v3 全程长按 -> 被打断时卡在蓄力里, 动作不连贯。
        现在是 v2 的形状 + v2 漏掉的那个"立刻按下"。

        【第 2 段里只有一次 mouse_down 和一次 mouse_up】: 中间【绝对不要】click()
        (会把按住松开)或者补 mouse_down()(内部投的 WM_ACTIVATE 会把按住打断)。
        技能键可以发 —— 爱琳莫那条轴上按住的同时发 E/R 是验过的。

        Args:
            e_after: 【点】这一段开始之后这么久发 E(None = 这一格没有 E)。
                轴上写 "aaa e z" 的那两处就是靠它把 E 插在连点中间。
            stop_when: 额外的提前结束判据。升天那一发传 on_air: 人已经上天了就不用
                再等条的读数(读数滞后, 每轮都要白按满上限)。
        Returns: 强化重击有没有确认放出去。
        """
        cap = self.MOR_HOLD_CAP if cap is None else cap
        # 【这么早"读到条满"一律不算】(用户 2026-08-22: "为什么有一段莫宁变奏入场
        # 直接就开R了")。实机那一轮: morHeavyFill(lit,A x1,0.02s) —— 她刚变奏入场,
        # 第一帧就读到条是满的, 于是 A123 那 2.2 秒【整段跳过】, E 补在 0.03 秒,
        # 重击 1.11 秒, R 1.62 秒 —— 画面上就是"入场直接开R"。
        # 那个读数是【上一个角色的 HUD 还没换掉】: 变奏那一刹那屏幕上还是清宵的状态,
        # 而回路条是按固定屏幕区域找图的。
        # 【这一格有 E 的时候, 下界还要至少等到 E 该发的时刻】——
        # 轴上就是"A 到 A3 再放 E 再接重击", 条再早满也不能把 A3 和 E 抢到前面去
        min_fill = self.MOR_FILL_MIN
        if e_after is not None:
            min_fill = max(min_fill, e_after)
        # ---- 1 点到强化重击亮 ----
        fill_start = time.time()
        clicks = 0
        e_sent = False
        lit = False
        lit_streak = 0
        next_click = 0.0
        last_pause = fill_start
        while self.time_elapsed_accounting_for_freeze(fill_start) < self.MOR_FILL_CAP:
            self.task.next_frame()
            now = time.time()
            try:
                lit_streak = lit_streak + 1 if mor.is_mouse_forte_full() else 0
            except Exception:
                lit_streak = 0
            if lit_streak >= self.MOR_FORTE_CONFIRM and now - fill_start >= min_fill:
                lit = True
                break          # 【立刻退出去按住, 不再多点一下】
            if e_after is not None and not e_sent and now - fill_start >= e_after:
                # 【一直重发到 E 真的进了 CD】(用户 2026-08-22: "E没进CD就重新尝试放呗")。
                # 单发/双发都赌"这一下没被动画吞掉"; 进没进 CD 是【能查的】——
                # task.get_cd('resonance') > 0 就是放出去了。查得到就别赌
                # 【重发 E 的期间不点普攻】(用户 2026-08-22: "变奏入场开始你就A和E
                # 连放, 这样不行啊, 还是最好先A到A3再放E接强化重击接RQ切人,
                # 这样最流畅, 你提前放了E会不流畅")。
                # 原来这里每发一次 E 就补一下点击, 画面上就是 A 和 E 交替往外蹦。
                # 现在是【A 打到 A3 -> 停手 -> 只发 E -> 接重击】, 一条线走下来
                e_end = time.time() + self.MOR_E_FIRE_TIME_OUT
                n_e = 0
                while time.time() < e_end:
                    if self.task.get_cd('resonance') > 0:
                        break
                    mor.send_resonance_key()
                    n_e += 1
                    self.macro_wait(self.MOR_E_RESEND_INTERVAL)
                    self.task.next_frame()
                fired_e = self.task.get_cd('resonance') > 0
                mor.record_resonance_use()
                e_sent = True
                self.macro_mark(f'{tag}E({"ok" if fired_e else "NOCD"},x{n_e},'
                                f'@{now - fill_start:.2f})')
                if not fired_e:
                    self.logger.warning(f'{tag}: E 发了 {n_e} 次也没进 CD —— '
                                        f'多半被入场/普攻动画一直吞着')
                # 【E 发完立刻转去按住, 不再回去点】(用户 2026-08-22: "E的同时就开始
                # 长按重击准备重击")。按住是预输入 —— E 的动画一结束、条一满,
                # 强化重击自己就出来了, 不用等我们"看到标记亮再按下去"那一整个往返。
                # 下面那一段的 full_seen 从 False 起算(lit 还是 False), 所以它会
                # 老老实实等"先看到条满、再看到条空", 不会一进去就假成立
                break
            # 【每隔一段停手让读数出来】(2026-08-22 实机): 循环轴里连点期间
            # is_mouse_forte_full 一次都读不到(她一直在出招, 那个图标没渲染出来),
            # 一停手长按就立刻读到满 —— 所以每 MOR_READ_EVERY 秒空出
            # MOR_READ_PAUSE 不点, 专门给读数一个窗口。代价是每轮少点两三下
            if now - last_pause >= self.MOR_READ_EVERY:
                if now - last_pause < self.MOR_READ_EVERY + self.MOR_READ_PAUSE:
                    continue          # 读数窗口: 只读不点
                last_pause = now
            if now >= next_click:
                self.click()
                clicks += 1
                next_click = now + self.MOR_A_INTERVAL
        # 【把"条到底亮没亮"留给调用方】: 启动轴那边要靠它区分"重击没打出来是因为
        # 资源没到"(该重试)还是"读不到条"(重试也没用), 见 opener_seg1
        self.mor_fill_lit = bool(lit)
        why_fill = 'lit' if lit else ('afterE' if e_sent else 'CAP')
        self.macro_mark(f'{tag}Fill({why_fill},A x{clicks},'
                        f'{time.time() - fill_start:.2f}s)')
        if not lit and not e_sent:
            # 【afterE 不算异常】: 那是"E 发完就转去按住"的正常路径, 条会在按住期间满
            self.logger.warning(
                f'{tag}: forte never lit in {self.MOR_FILL_CAP:.1f}s ({clicks} clicks) — '
                f'接下来按下去的是普通重击')
        if e_after is not None and not e_sent:
            # 条比预定的 E 时刻先亮: E 还是要发, 补在按住之前(轴上它在重击之前)
            mor.send_resonance_key()
            mor.record_resonance_use()
            self.macro_mark(f'{tag}E@lit')

        # ---- 2 按住, 等它出手 ----
        # 【按下去这一刻的协奏读数留个底】: 后面 mor_wait_hit 靠"协奏涨了没有"判断
        # 重击打没打中 —— 按住期间没有别的攻击, 所以涨的只可能是这一发
        try:
            self.mor_hold_con0 = float(mor.get_current_con())
        except Exception:
            self.mor_hold_con0 = None
        self.task.mouse_down()
        self.holding_attack = True
        self.macro_mark(f'{tag}_down(con{self.mor_hold_con0 if self.mor_hold_con0 is None else round(self.mor_hold_con0, 2)})')
        start = time.time()
        full_streak = 0
        empty_streak = 0
        # 上一段是"点到亮"才出来的, 所以进来时条就是满的 —— 直接认, 免得读数抖一下
        # 就要重新等它"再亮一次"
        full_seen = bool(lit)
        fired = False
        why = 'CAP'
        trace = []
        last_sample = 0.0
        try:
            while self.time_elapsed_accounting_for_freeze(start) < cap:
                self.task.next_frame()
                now = time.time()
                if stop_when is not None:
                    try:
                        if stop_when():
                            fired, why = True, 'stop'
                            break
                    except Exception:
                        pass
                try:
                    full = bool(mor.is_mouse_forte_full())
                except Exception:
                    full = False
                if now - last_sample >= self.MOR_HOLD_SAMPLE:
                    last_sample = now
                    trace.append(f'{now - start:.1f}:{int(full)}')
                # 【判据是"条从满掉到空"】。进这一段时条【已经是满的】(上一段就是
                # 点到它亮才出来的), 所以这里其实只等它掉下去; full_seen 那一步是
                # 兜"上一段跑满上限、条其实没亮"的情况, 免得一进来就假成立。
                # 满和空都连着读到 MOR_FORTE_CONFIRM 帧才认 —— 清宵那边的假阳性
                # 就是"亮去了抖、灭没去抖"造成的, 这里两边对称
                if full:
                    full_streak += 1
                    empty_streak = 0
                else:
                    empty_streak += 1
                    full_streak = 0
                if full_streak >= self.MOR_FORTE_CONFIRM:
                    full_seen = True
                elif full_seen and empty_streak >= self.MOR_FORTE_CONFIRM:
                    fired, why = True, 'forte'
                    break
                # 【读不到条的那一轮别按到上限】(用户 2026-08-22: "重击了应该马上接F,
                # 没马上接又A了几下才接的")。
                # 实机 morAirHeavy_up(CAP,3.04s): 空中读不到回路条(爱琳莫早就记过),
                # 于是"先满再空"这个判据永远不成立, 一路按满 3 秒 —— 而重击早在
                # 头一秒就出手了, 后面两秒纯粹是按着不放, 把后面的处决整个推迟。
                # 判据读不到时就退化成【按固定时长】(跟改成读数判据之前的行为一样),
                # 读得到的轮次不受影响
                if not full_seen and \
                        self.time_elapsed_accounting_for_freeze(start) >= self.MOR_HOLD_BLIND:
                    why = 'blind'
                    break
                self.macro_wait(0.01)
        finally:
            self.release_attack()
        self.macro_mark(f'{tag}_up({why},{time.time() - start:.2f}s)')
        self.logger.info(f'{tag} forte trace: {" ".join(trace)}')
        if not fired:
            self.logger.warning(
                f'{tag}: heavy never confirmed in {time.time() - start:.2f}s of holding '
                f'(forte seen full={full_seen}) — 看上面那行 trace: '
                f'条一直是 0 就是压根没充上去(被打断了?), 一直是 1 就是它没掉下来(判据要换)')
        return fired

    def hold_heavy(self, char, cap, min_hold=0.20, tag='长按重击',
                   skip_if_dark=False, held_since=None, full_probe=None):
        """按住左键出重击, 【提示一消失就松手】。

        【为什么不用原版的 heavy_click_forte】: 那个进门先读一次屏判断提示在不在,
        读到不在就整段跳过 —— 而我们是刚从 wait_mouse_forte 出来的, 那一次读屏是
        纯重复; 更麻烦的是它的 wait_until 上限写死 2 秒, 这里三个人要的上限不一样。

        【min_hold 是必需的】: 提示图标在起手那几帧会闪一下, 不压一个下界的话
        第一帧就会误判成"招已经出去了"当场松手, 重击根本没蓄出来。

        【松手不会取消已经出去的招】: 强化重击/观测重击是完整的一整段动作,
        按住只是把它【触发】出来 —— 触发之后松手, 它照样演完。所以这里越早松手
        越好, 后面那一发 R 才能贴着解锁帧打断它。
        """
        # 【按下去之前先记一笔提示状态】: 出问题时这一条能直接分清是
        # "根本没准备好就长按"(灭) 还是 "按了但没蓄出来"(亮)
        # 【full_probe: 换一个读得到的判据】: 框架的 is_mouse_forte_full 是模板匹配,
        # 在弗洛洛身上会漏(实机连拍抓到过: 指示一直亮着, 模板却判暗)。
        # 这一格的颜色判据见 PHRO_FORTE_BOX
        probe = full_probe or (lambda: bool(char.is_mouse_forte_full()))
        if held_since is not None:
            # 【手已经按在上面了】(预输入): 进门那次读屏和 mouse_down 全跳过 ——
            # 见 PHRO_PREHOLD。min_hold 也要从【真正按下去的那一刻】算,
            # 不然会白等一遍
            lit_at_entry = True
        else:
            try:
                self.task.next_frame()
                lit_at_entry = probe()
            except Exception:
                lit_at_entry = None
        if skip_if_dark and lit_at_entry is False:
            # 【提示没亮就干脆不按】: 莫宁那一格用这个 —— 提示灭着长按出来的是
            # 普通空中重击, 而"施放空中攻击下落"会把观测状态直接移除,
            # 比什么都不做还糟。什么都不做的话状态还在, 下一格照样能走
            self.macro_mark(f'{tag}(提示灭,跳过)')
            self.logger.warning(f'{tag}: prompt not lit, skipping the hold entirely '
                                f'(a plain heavy would drop the state)')
            return False
        if held_since is None:
            self.task.mouse_down()
            self.holding_attack = True
        start = held_since if held_since is not None else time.time()
        fired = False
        try:
            if min_hold > 0:
                self.macro_wait(min_hold)
            while time.time() - start < cap:
                self.task.next_frame()
                try:
                    if not probe():
                        fired = True
                        break
                except Exception:
                    pass
                self.macro_wait(0.02)
        finally:
            self.release_attack()
        self.macro_mark(f'{tag}(按下时{"亮" if lit_at_entry else "灭" if lit_at_entry is not None else "?"},'
                        f'{"出" if fired else "cap"},{time.time() - start:.2f}s)')
        if lit_at_entry is False:
            self.logger.warning(f'{tag}: the heavy prompt was NOT lit when the hold '
                                f'started — this will come out as a plain heavy')
        return fired

    def hold_through_lib(self, tag='预输入重击', time_out=None, tail=0.0,
                         f_interval=None, settle=0.0):
        """演出期间【一直按住左键】(预输入重击), 顺带可以一直按处决键。

        坎特蕾拉那一格专用: 演出结束的第一帧就要有一个重击落进去, 她才能无缝接上
        重击·浮潜幻海(帧表第22F给 8 秒强化状态)。

        【为什么是按住而不是连点】: 重击是长按出的招, 连点只会打出普攻。
        而演出期间的输入是被丢掉的、不排队 —— 所以唯一可行的形状就是"一直按着",
        让游戏在放行的第一帧读到"左键处于按下状态"。

        【为什么不能只按 tail 那一段】: 演出结束的时刻是浮动的(大招哪一帧出手不定),
        等 HUD 回来再按下就已经晚了半拍, 中间那一下会变成普攻。

        Args:
            f_interval: 顺带按处决键的间隔(None = 不按)。
                【处决就该放在这里】(用户 2026-08-31: "能不能把F放到坎R后?
                R的时候不是要预输入重击吗, 这个预输入放在处决动画里, 坎R了就一直按F")。
                好处是【两段演出串在一起, 只花一次预输入】: 大招演完 -> 处决接上 ->
                处决演完 -> 那一下重击落在最后, 8 秒强化状态从那一刻才开始烧。
                【比掺在后面的 A/E 连发里好】: 那样 F 会把她的普通 E 打断(实机验证过)。
            settle: 【HUD 要连续回来这么久才算演出真的完了】。
                大招演完到处决演出开始之间 HUD 会短暂回来一下 —— 一看到就退的话,
                预输入正好卡在两段演出中间, 重击会在处决动画里被吃掉。
        """
        time_out = self.LIB_ANIM_TIME_OUT if time_out is None else time_out
        self.task.mouse_down()
        self.holding_attack = True
        start = time.time()
        gone_seen = False
        back = False
        nf = 0
        back_since = None
        next_f = start
        try:
            while time.time() - start < time_out:
                now = time.time()
                if f_interval and self.USE_F_BREAK and now >= next_f:
                    self.task.send_key('f', after_sleep=0)
                    nf += 1
                    next_f += f_interval
                    if next_f < now:
                        next_f = now + f_interval
                self.task.next_frame()
                if not self.task.in_team()[0]:
                    gone_seen = True
                    back_since = None
                elif gone_seen or time.time() - start >= self.HUD_NO_ANIM_GRACE:
                    # 【要连续在场 settle 秒才认】: 两段演出之间 HUD 会闪回来一下
                    if back_since is None:
                        back_since = time.time()
                    if time.time() - back_since >= settle:
                        back = True
                        break
                self.macro_wait(0.01)
            if tail > 0:
                self.macro_wait(tail)
        finally:
            self.release_attack()
        # 演出这一段计入 freeze, 否则框架的 time_elapsed_accounting_for_freeze
        # 会把它算成"这个角色磨蹭了 4 秒"
        self.add_freeze_duration(start, time.time() - start)
        self.macro_mark(f'{tag}({"ok" if back else "timeout"},'
                        f'{"anim" if gone_seen else "NOANIM"}'
                        f'{f",F x{nf}" if nf else ""},'
                        f'{time.time() - start:.2f}s)')
        return back

    # ==================== 弗洛洛段(启动/循环共用) ====================

    def seg_phrolova(self, mor, opener=False):
        """攒 6 个乐声 -> 长按重击 -> 大招 -> 变奏莫宁。

        【乐声怎么来的】(帧表 弗洛洛 核心回收1): A3、强化A、E、强化E 各给 1 层,
        上限 6 层, 大招一次吃掉 6 层。所以这一段就是"连点普攻 + 中间插一发 E",
        A3 -> 强化A -> (E) -> 强化A -> A3 -> 强化A 正好六个。
        【连段是自己推的, 不用数】: 打到 A3 之后下一下 A 自动变强化A, 再下一下又从
        A1 起 —— 所以除了那一发 E, 全程就是连点, 不需要按段数分窗口。

        Args:
            opener: 启动轴走这条。【两条轴的入场方式不一样】——
                启动轴是手动切人(连段从 A1 起、没有输入锁),
                循环轴是变奏入场(QTE 复用 A2, 有 77 帧输入锁), 所以参数分两档。
        """
        # 【没拿到变奏就走"手动切人"那一档】: 上一格协奏没填满时 handoff 会把
        # has_intro 记成 False —— 那这次进场就【没有 QTE 那 1.28 秒输入锁】,
        # 还按变奏那档等就是白站 1.3 秒, 后面每一格跟着错位。
        # (那种情况本身是个 bug, 坎那边会打 warning; 这里只是别让它雪上加霜)
        no_intro = (not opener) and (not self.has_intro)
        if no_intro:
            self.logger.warning('phrolova: came in WITHOUT an intro — 上一格协奏没满。'
                                '这一圈按手动切人那一档跑')
        if opener or no_intro:
            # 手动切人进来的, 没有变奏的输入锁, 给一点点稳定时间就能开打。
            # 【用 macro_gap 不用 macro_wait】: 持续普攻这时已经打开, 这一小段也该在打
            self.macro_gap(self.O_ENTER_SETTLE, tag='弗A')
            a_to_e = self.O_PHRO_ENTER_TO_E
        else:
            # 【变奏入场这一段不许出手】: QTE 第77F前不响应输入, 发出去的键全丢。
            # 用 poll_wait 不用 macro_wait —— 纯等待期间画面是冻的, 战斗判定线程
            # 拿到旧帧会误判 target lost
            self.poll_wait(self.PHRO_INTRO_LOCK, tag='弗入场锁')
            a_to_e = self.L_PHRO_INTRO_TO_E

        self.poking = True
        # 【这里原来有一段 macro_spam(a_to_e) 盲打】—— 已经去掉了:
        # 那 1.35 秒里没人看环, 强化普攻亮了也白亮, 第一次闪避因此迟到 1.1 秒
        # (用户 2026-09-01)。现在起手那几下 A 由 phro_ea_cycle 自己的连点打,
        # 下界见 O_PHRO_EA_MIN_A / L_PHRO_EA_MIN_A
        # ---- 强化普攻循环 ----: 见 phro_ea_cycle / PHRO_EA_DELAY 那一段
        # 【这里换掉了原来那串 E -> 强化E -> Q -> 连点等闸门】(用户 2026-09-01
        # 重新给的流程)。原来那套的所有零件都还在(press_e_until_fired /
        # phro_press_ee / wait_heavy_ready), 只是不在这条路上了
        # 【循环轴开预输入】(用户 2026-09-01: "检测小鼠标亮起一瞬间开始预输入重击")。
        # 启动轴不开: 它的闸门是"音符满 AND 协奏够", 协奏那一条可能比音符晚很多,
        # 提前按住会在等协奏的那段时间里空放一发普通重击
        self.phro_ea_cycle(opener, prehold=(not opener) and self.PHRO_PREHOLD)

        # ---- 长按重击 -> 强化重击 -> R 大招。【打不出来就重来, 不许直接切人】 ----
        # 理由见 PHRO_LIB_TRIES 那一段
        fired_lib = False
        for attempt in range(1, self.PHRO_LIB_TRIES + 1):
            if attempt > 1:
                # 【重试前先把提示等回来】: 被打断之后乐声还在, 提示通常还亮着,
                # 这一步几乎不花时间; 等不到就直接再长按一次试试(强化重击"技能中断后"
                # 也会解锁大招, 说不定上一次已经解锁了, 只是 R 被吞了)
                self.poking = True
                self.wait_mouse_forte(self, cap=self.PHRO_RETRY_WAIT,
                                      min_wait=0.20,
                                      interval=self.PHRO_A_INTERVAL,
                                      tag=f'弗重击提示{attempt}')
            # 【长按期间不点】: hold_heavy 是按住左键, 再插点击只会把长按打断
            self.poking = False
            # 【第一轮接手预输入那只手】: prehold_at 是按下去的时刻, min_hold 从那里算;
            # 重试轮次没有预输入, 老老实实自己按
            # 【指示没亮就整发不打】(skip_if_dark): 那样出来的是普通重击 ——
            # 没有那 40 点协奏、也拿不到定音状态(大招不解锁), 比不打还糟。
            # 【这条是用户给的硬要求】(2026-09-01: "需要同时满足协奏值35以及
            # 重击检测亮起才可以重击R")
            self.hold_heavy(self, cap=self.PHRO_HEAVY_CAP,
                            min_hold=self.PHRO_HEAVY_MIN, skip_if_dark=True,
                            held_since=(self.prehold_at if attempt == 1 else None),
                            full_probe=lambda: self.phro_forte_full(self)[0],
                            tag='弗长按重击' if attempt == 1 else f'弗长按重击{attempt}')
            # 强化重击第139F(2.32秒)解锁大招, 所以 R 要一直重发到演出真的开始。
            # 【这几秒里必须继续连点】(poke=True): 不点的话她就是站着按 R
            if self.fire_lib(self, tag='R弗大招' if attempt == 1 else f'R弗大招{attempt}',
                             window=self.PHRO_HEAVY_TO_LIB,
                             poke=True, click_interval=self.PHRO_A_INTERVAL):
                fired_lib = True
                break
            self.prehold_at = None
            self.logger.warning(f'phrolova: 第 {attempt} 轮"重击+R"没放出来 —— '
                                f'多半是长按被打断了。乐声不会因此清掉, 接着打再来一次')
        if fired_lib:
            self.poke_until_hud_back(tag='弗大招Anim',
                                     time_out=self.PHRO_LIB_ANIM + 3)
        else:
            # 【试满还是不行才往下走】: 卡死比少一发大招更糟, 但要吼出来 ——
            # 这一圈莫宁那一段会整个错位(她的流程建立在"弗洛洛在指挥状态"上)
            self.logger.warning(
                f'phrolova: {self.PHRO_LIB_TRIES} 轮都没把大招放出来, 照样交棒 —— '
                f'这一圈少一发大招。往上游查: 六乐声那一格是不是根本没满'
                f'(看 重击闸门 那一行的"乐声"字段)')

        # ---- 演出完补几下把协奏顶满 -> 变奏莫宁 ----
        # 大招-前置 协奏回收20, 演出结束时协奏基本就是满的, 所以这一格实测只要 0.85 秒
        self.poking = True
        self.wait_con_for_intro(self, 'Mornye', poke=True,
                                time_out=self.PHRO_POST_LIB_CON)
        self.quick_switch(mor, read_con=True, click_during=True)
        self.poking = False

